"""瀏覽器實測：建立頁自動帶入編號 → 建立 → 瀏覽所有合約 → 查詢 → 合約內容頁 → 切英文 → 改編號。"""
import asyncio, sys
from playwright.async_api import async_playwright
BASE = (sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:5055").rstrip("/")
async def main():
    ok = []
    def check(n, c, d=""): ok.append(bool(c)); print(("PASS " if c else "FAIL ") + n + (f"  [{d}]" if d and not c else ""))
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport={"width": 1280, "height": 900})
        errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
        await pg.goto(BASE + "/"); await pg.wait_for_function("document.getElementById('c-no').value.startsWith('C-')", timeout=20000)
        no = await pg.input_value("#c-no"); check("建立頁自動帶入 C-YYMM001", no.endswith("001"), no)
        await pg.fill("#c-title", "瀏覽器測試合約")
        es = pg.locator(".signer-email"); await es.nth(0).fill("ua@example.com"); await es.nth(1).fill("ub@example.com")
        await pg.locator(".signer-company").nth(0).fill("全球科技股份有限公司")
        await pg.locator(".signer-tax").nth(0).fill("12345678")
        await pg.locator(".signer-address").nth(0).fill("台北市信義區信義路五段 7 號")
        await pg.locator(".signer-rep").nth(0).fill("王大明")
        await pg.click("#create-btn"); await pg.wait_for_timeout(500)
        check("錯誤統編在送出前就提示", "統一編號不正確" in await pg.inner_text("#create-msg"), await pg.inner_text("#create-msg"))
        await pg.locator(".signer-tax").nth(0).fill("04595257")
        await pg.locator(".signer-row").nth(0).screenshot(path="/tmp/ui_signer.png")
        await pg.click("#create-btn"); await pg.wait_for_selector("#preview-card:not([hidden])", timeout=30000)
        pv = await pg.inner_text("#owner-preview")
        check("封面顯示公司名稱、統編、代表人", "全球科技股份有限公司" in pv and "04595257" in pv and "王大明" in pv, pv[:200])
        check("預覽封面顯示合約編號", no in await pg.inner_text("#owner-preview"))
        await pg.wait_for_function(f"document.getElementById('c-no').value !== '{no}'", timeout=15000)
        check("建立後自動換成下一號", (await pg.input_value("#c-no")).endswith("002"))
        await pg.click("#top-nav a[data-nav=list]"); await pg.wait_for_selector(".c-row", timeout=20000)
        check("瀏覽所有合約顯示這份合約", no in await pg.inner_text("#list-body"))
        await pg.fill("#q", "不存在的關鍵字"); await pg.wait_for_function("document.getElementById('list-body').innerText.includes('沒有符合')", timeout=15000)
        check("查詢無結果時有提示", True)
        await pg.fill("#q", no); await pg.wait_for_selector(".c-row", timeout=15000)
        check("用編號查詢找得到", await pg.locator(".c-row").count() == 1 and "q=" in pg.url, pg.url)
        await pg.click(".c-row"); await pg.wait_for_function("document.getElementById('d-title').innerText === '瀏覽器測試合約'", timeout=20000)
        check("合約內容頁顯示公司資料", "信義路五段" in await pg.inner_text("#d-parties"))
        check("合約內容頁顯示封面與條款", no in await pg.inner_text("#d-content") and "第一條" in await pg.inner_text("#d-content"))
        await pg.click("#d-lang button[data-l=en]"); await pg.wait_for_function("!document.getElementById('d-content').innerText.includes('翻譯中')", timeout=30000)
        check("合約內容頁可切換英文", "[en]" in await pg.inner_text("#d-content") or "Terms" in await pg.inner_text("#d-content"))
        await pg.fill("#d-no", "UI-TEST-9"); await pg.click("#d-no-save"); await pg.wait_for_function("location.pathname.endsWith('UI-TEST-9')", timeout=15000)
        check("改編號後網址同步更新", "UI-TEST-9" in await pg.inner_text("#d-no-label"))
        await pg.goto(BASE + "/contracts/UI-TEST-9"); await pg.wait_for_function("document.getElementById('d-title').innerText === '瀏覽器測試合約'", timeout=20000)
        check("直接用編號網址開啟合約", True)
        await pg.set_viewport_size({"width": 390, "height": 844}); await pg.goto(BASE + "/contracts"); await pg.wait_for_selector(".c-row", timeout=20000)
        await pg.screenshot(path="/tmp/ui_list_mobile.png", full_page=True)
        await pg.set_viewport_size({"width": 1280, "height": 900}); await pg.screenshot(path="/tmp/ui_list.png")
        await pg.goto(BASE + "/contracts/UI-TEST-9"); await pg.wait_for_function("document.getElementById('d-title').innerText === '瀏覽器測試合約'", timeout=20000)
        await pg.screenshot(path="/tmp/ui_detail.png")
        check("頁面沒有 JavaScript 錯誤", not errs, errs[:2])
        await b.close()
    print(f"\n瀏覽器測試：{sum(ok)}/{len(ok)} 通過"); sys.exit(0 if all(ok) else 1)
asyncio.run(main())
